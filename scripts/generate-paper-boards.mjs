/**
 * Generate the printed-board registry: 50 boards per size (3/4/5), each with a
 * stable human-typable ID whose FIRST DIGIT IS THE SIZE — board 517 is the 17th
 * 5×5 card. Output: server/paper-boards.js
 *
 * ⚠️  DO NOT REGENERATE AFTER THE BOARDS HAVE BEEN PRINTED. The IDs on the
 * printed sheets must keep matching the cells stored here, or the host's
 * tracking silently tracks the wrong cards. (This is also why the file is
 * committed rather than built on the fly.)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { generateBoard } from '../server/game.js';

const PER_SIZE = 50;
const seen = new Set();
const boards = [];

for (const size of [3, 4, 5]) {
  for (let n = 1; n <= PER_SIZE; n += 1) {
    let cells;
    // Uniqueness is astronomically likely anyway; the loop makes it certain.
    do {
      cells = generateBoard(size);
    } while (seen.has(JSON.stringify(cells)));
    seen.add(JSON.stringify(cells));

    boards.push({ id: `${size}${String(n).padStart(2, '0')}`, size, cells });
  }
}

const header = `/**
 * GENERATED by scripts/generate-paper-boards.mjs — DO NOT EDIT, and DO NOT
 * REGENERATE once sheets have been printed: the printed IDs must keep matching
 * these cells forever, or the host's paper tracking tracks the wrong cards.
 *
 * ID scheme: first digit = board size, rest = serial. 517 = 5×5 card #17.
 */
export const PAPER_BOARDS = `;

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../server/paper-boards.js');
writeFileSync(out, header + JSON.stringify(boards) + ';\n');
console.log(`wrote ${boards.length} boards -> ${out}`);
